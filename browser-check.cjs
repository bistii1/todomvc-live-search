const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({ channel: 'chrome', headless: true });
 const page = await browser.newPage({ viewport: { width: 1200, height: 900 }, deviceScaleFactor: 1 });
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 const results=[];
 const titles=()=>page.locator('.todo-list li label').allTextContents();
 const count=async n=>page.waitForFunction(n=>document.querySelectorAll('.todo-list li').length===n,n);
 const add=async title=>{await page.locator('.new-todo').fill(title);await page.locator('.new-todo').press('Enter');};
 const route=async name=>{await page.getByRole('link',{name,exact:true}).click();await page.waitForFunction(name=>document.querySelector('.filters .selected').textContent===name,name);};
 const check=(name)=>{results.push('PASS: '+name);console.log('PASS: '+name);};
 await page.goto('http://127.0.0.1:7002');
 const initialScripts=await page.locator('script').count();
 await add('Read graph algorithms paper');await add('Implement search filter');await add('Review search tests');await add('Buy groceries');
 await page.locator('.todo-list li').filter({hasText:'Review search tests'}).locator('.toggle').check();
 await count(4);check('Create and complete tasks');
 const search=page.locator('input[type="search"]');
 await search.fill('  SEARCH  ');await count(2);
 assert.deepEqual((await titles()).sort(),['Implement search filter','Review search tests']);
 await page.screenshot({path:'docs/screenshots/02-search-all.png',fullPage:true});check('Trimmed, case-insensitive substring search');
 await route('Active');await count(1);assert.deepEqual(await titles(),['Implement search filter']);
 await page.screenshot({path:'docs/screenshots/03-search-active.png',fullPage:true});check('Search composes with Active and preserves query');
 await route('Completed');await count(1);assert.deepEqual(await titles(),['Review search tests']);check('Search composes with Completed');
 await route('All');await count(2);await search.fill('xyz-no-task');await count(0);
 assert.match(await page.locator('body').innerText(),/no .*match/i);
 await page.screenshot({path:'docs/screenshots/04-no-matches.png',fullPage:true});check('No-match feedback');
 await search.press('Escape');await count(4);assert.equal(await search.inputValue(),'');check('Escape clears query');
 await search.fill('search');await count(2);await page.getByRole('button',{name:/clear search/i}).click();await count(4);assert.equal(await search.inputValue(),'');check('Clear search button');
 await search.fill('search');await count(2);await add('Search new task');await count(3);await add('Another unrelated task');await count(3);check('New tasks respect current query');
 let item=page.locator('.todo-list li').filter({hasText:'Implement search filter'});
 await item.locator('label').dblclick();await item.locator('.edit').fill('Plan release');await item.locator('.edit').press('Enter');await count(2);check('Editing a title removes a nonmatching result');
 await route('Active');await count(1);
 await page.locator('.todo-list li .toggle').click();await count(0);check('Completion refreshes composed search');
 await route('Completed');await count(2);
 await page.locator('.todo-list li').filter({hasText:'Search new task'}).hover();await page.locator('.todo-list li').filter({hasText:'Search new task'}).locator('.destroy').click();await count(1);check('Deletion refreshes results');
 await page.getByRole('button',{name:/clear search/i}).click();await route('All');await count(5);
 await search.fill('groceries');await count(1);
 await page.getByRole('button',{name:'Clear completed',exact:true}).click();await count(1);
 await search.press('Escape');await count(4);assert.ok(!(await titles()).includes('Review search tests'));check('Clear completed retains global semantics during search');
 await search.fill('groceries');await count(1);
 await page.locator('.toggle-all-label').click();await route('Completed');await count(1);
 await search.press('Escape');await count(4);check('Toggle all retains global semantics during search');
 await route('All');await search.fill('<script>');await count(0);assert.equal(await page.locator('script').count(),initialScripts);check('Special-character query is treated as text');
 await search.fill('groceries');await count(1);
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);await page.screenshot({path:'docs/screenshots/05-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);check('Mobile layout fits 390-pixel viewport');
 await page.reload();await add('Only task');await search.fill('only');await count(1);
 await page.locator('.todo-list li').hover();await page.locator('.todo-list li .destroy').click();await count(0);
 assert.equal(await search.isVisible(),true);await page.getByRole('button',{name:/clear search/i}).click();assert.equal(await search.inputValue(),'');check('Search remains usable after deleting the last task');
 await search.fill('   ');assert.equal(await page.getByRole('button',{name:/clear search/i}).isEnabled(),true);
 await page.getByRole('button',{name:/clear search/i}).click();assert.equal(await search.inputValue(),'');check('Whitespace-only query can be cleared by button');
 assert.deepEqual(errors,[]);check('No uncaught browser errors');
 fs.writeFileSync('docs/test-results.txt',results.join('\n')+'\n');console.log(results.join('\n'));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
